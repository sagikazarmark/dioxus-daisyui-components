// Keeps the generated Tailwind stylesheet out of `git status` without a
// .gitignore rule.
//
// `assets/style.css` is build output, but it cannot be listed in any
// .gitignore: Dagger reads the workspace with `gitignore: true` (the Dioxus
// module builds the Preview from `Workspace.directory("/", gitignore: true)`),
// and on Dagger Cloud, which reads the workspace from the git ref, that applies
// every .gitignore file. The stylesheet `dagger.dang` generates and overlays
// into the workspace would be dropped again, and the Preview would fail to
// compile with "Asset at assets/style.css doesn't exist".
//
// Git also reads the clone's own `info/exclude`, which never leaves the clone,
// so the rule goes there. `npm run build` and `npm run watch` run this first.
// Outside a git checkout, as in the Dagger build container, it does nothing.

import { execFileSync } from "node:child_process";
import { appendFileSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname } from "node:path";

const rule = "/assets/style.css";

let exclude;
try {
  exclude = execFileSync("git", ["rev-parse", "--git-path", "info/exclude"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();
} catch {
  process.exit(0);
}

const current = existsSync(exclude) ? readFileSync(exclude, "utf8") : "";
if (!current.split(/\r?\n/).includes(rule)) {
  mkdirSync(dirname(exclude), { recursive: true });
  const separator = current === "" || current.endsWith("\n") ? "" : "\n";
  appendFileSync(exclude, `${separator}# Generated by npm run build; see scripts/exclude-generated.mjs\n${rule}\n`);
}
